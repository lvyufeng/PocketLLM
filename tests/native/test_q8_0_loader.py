"""The `q8_0` block decoder, against the tree's own Python one.

`src/quant/q8_0.h` is the C++ side of a format the Python package already decodes
(`pocketllm.quant.k_quants.dequantize_q8_0`), so the two are a check on each other:
the Python one is the specification here, and the C++ one is what the audio tower's
loader will actually call.

The comparison runs over a real tensor out of a real checkpoint rather than over
synthetic bytes, because the interesting failures are in the *layout* -- which two
bytes are the scale, whether the values are signed, whether the blocks are
contiguous -- and synthetic input generated by the same understanding as the decoder
would agree with it about all of those.

The tensor is one of the audio tower's, which is why the checkpoint is the Qwen3-ASR
mmproj: it is the file in this tree whose weights are `q8_0`, and the format is not
otherwise reachable.
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import textwrap

import numpy as np
import pytest

from pocketllm.loader.gguf.reader import GGUFReader
from pocketllm.quant import k_quants

MMPROJ = pathlib.Path("/mnt/data1/models/mmproj-Qwen3-ASR-1.7B-Q8_0.gguf")

#: One attention projection: small enough to compare whole, and `q8_0` in this file.
TENSOR = "a.blk.0.attn_q.weight"

pytestmark = pytest.mark.skipif(
    not MMPROJ.is_file(), reason=f"no q8_0 checkpoint at {MMPROJ}"
)


def _compile(tmp_path: pathlib.Path) -> pathlib.Path:
    """A tiny C++ program that decodes the tensor with the header under test."""
    source = tmp_path / "decode.cpp"
    source.write_text(
        textwrap.dedent(
            """
            #include <cstdio>
            #include <cstdlib>
            #include <vector>

            #include "gguf/reader.h"
            #include "quant/q8_0.h"

            int main(int argc, char **argv) {
              const pocketllm::GgufReader reader(argv[1]);
              const std::string name = argv[2];
              uint64_t nbytes = 0;
              const uint8_t *packed = reader.tensor_data(name, &nbytes);
              const pocketllm::GgufTensorInfo *info = reader.tensor(name);
              int64_t elements = 1;
              for (uint64_t dim : info->dimensions) {
                elements *= static_cast<int64_t>(dim);
              }
              std::vector<float> out(static_cast<size_t>(elements));
              pocketllm::quant::q8_0_dequantize(packed, elements, out.data());
              std::fwrite(out.data(), sizeof(float), out.size(), stdout);
              return 0;
            }
            """
        )
    )
    root = pathlib.Path(__file__).resolve().parents[2]
    binary = tmp_path / "decode"
    result = subprocess.run(
        [
            "g++",
            "-O2",
            "-std=c++17",
            f"-I{root / 'src'}",
            str(source),
            str(root / "src" / "gguf" / "reader.cpp"),
            str(root / "src" / "abi" / "spec.cpp"),
            "-o",
            str(binary),
        ],
        capture_output=True,
        text=True,
    )
    # `fail`, not `skip`: the probe is this file's whole instrument, and a compiler
    # problem in it is a broken test rather than an absent one.  A skip here would
    # report green on a probe that no longer builds, which is how a comparison stops
    # being run without anyone noticing.
    if result.returncode != 0:
        pytest.fail(f"cannot build the decoder probe: {result.stderr[-600:]}")
    return binary


def test_the_q8_0_decoder_agrees_with_the_python_one(tmp_path: pathlib.Path) -> None:
    binary = _compile(tmp_path)

    # The Python side needs the *packed* bytes, not a decoded tensor: the question
    # is whether the C++ decoder and the Python one read the same layout, and handing
    # the C++ side an already-decoded array would answer a different question.  So the
    # tensor's offset and length come from the reader and the bytes are read directly.
    parsed = GGUFReader(str(MMPROJ)).read()
    info = parsed.tensors_by_name[TENSOR]
    assert info.nbytes is not None
    with open(MMPROJ, "rb") as handle:
        handle.seek(info.absolute_offset)
        packed = handle.read(info.nbytes)
    assert len(packed) == info.nbytes
    # The decoder takes blocks, not a flat byte run: `(n_blocks, 34)`.
    blocks = np.frombuffer(packed, dtype=np.uint8).reshape(-1, k_quants.Q8_0_BLOCK_BYTES)
    expected = k_quants.dequantize_q8_0(blocks)

    result = subprocess.run([str(binary), str(MMPROJ), TENSOR], capture_output=True)
    assert result.returncode == 0, result.stderr.decode()
    got = np.frombuffer(result.stdout, dtype="<f4")

    expected = expected.reshape(-1).astype(np.float32)
    assert got.size == expected.size, f"decoded {got.size} weights, expected {expected.size}"
    # Bit-identical, not close: both sides decode `d * qs[i]` in f32, so any
    # difference is a layout mistake rather than rounding.
    differing = int(np.count_nonzero(got != expected))
    assert differing == 0, (
        f"{differing} of {got.size} weights differ between the C++ decoder and the Python "
        f"one; worst {float(np.abs(got - expected).max())}"
    )